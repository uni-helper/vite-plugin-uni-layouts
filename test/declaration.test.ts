import { mkdtemp, readdir, readFile, rm, stat, utimes, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import ts from 'typescript'
import { afterEach, expect, it, vi } from 'vitest'
import { runtimeModuleCode, virtualModuleId } from '../src/constant'
import { getDeclaration, writeDeclaration } from '../src/declaration'

let dir: string | undefined

afterEach(async () => {
  vi.restoreAllMocks()
  if (dir)
    await rm(dir, { recursive: true, force: true })
  dir = undefined
})

async function getDir(): Promise<string> {
  dir = await mkdtemp(join(tmpdir(), 'uni-layouts-'))
  return dir
}

function getExports(code: string): string[] {
  return [
    ...code.matchAll(/export (?:function|const|let|class) (\w+)/g),
  ]
    .map(match => match[1])
}

it('generated declaration is valid TypeScript', () => {
  const { diagnostics } = ts.transpileModule(getDeclaration(), {
    reportDiagnostics: true,
  })
  expect(diagnostics ?? []).toHaveLength(0)
})

it('generated declaration declares exactly the virtual module exports', () => {
  const declaration = getDeclaration()
  expect(declaration).toContain(`'${virtualModuleId}'`)

  const runtimeExports = getExports(runtimeModuleCode)
  expect(runtimeExports.length).toBeGreaterThan(0)
  // an export that only the declaration has would override the same name from
  // client.d.ts without any error, so the sets must match
  expect(getExports(declaration).sort()).toEqual(runtimeExports.sort())
})

it('writes the declaration file', async () => {
  const file = join(await getDir(), 'types', 'uni-layouts.d.ts')
  await writeDeclaration(file)
  expect(await readFile(file, 'utf-8')).toBe(getDeclaration())
})

it('leaves no temporary file behind', async () => {
  const dirPath = await getDir()
  await writeDeclaration(join(dirPath, 'uni-layouts.d.ts'))
  expect(await readdir(dirPath)).toEqual(['uni-layouts.d.ts'])
})

it('leaves an up-to-date file untouched', async () => {
  const file = join(await getDir(), 'uni-layouts.d.ts')
  await writeDeclaration(file)

  // a rewrite would reset the timestamp
  const old = new Date(2000, 0, 1)
  await utimes(file, old, old)
  await writeDeclaration(file)
  expect((await stat(file)).mtime.getFullYear()).toBe(2000)
})

it('updates a file from an older version of the plugin', async () => {
  const file = join(await getDir(), 'uni-layouts.d.ts')
  await writeFile(file, '// Generated by vite-plugin-uni-layouts\n\nstale declaration\n')
  await writeDeclaration(file)
  expect(await readFile(file, 'utf-8')).toBe(getDeclaration())
})

it('does not overwrite a hand-written file', async () => {
  const file = join(await getDir(), 'uni-layouts.d.ts')
  const handWritten = 'declare module \'my-types\' {}\n'
  await writeFile(file, handWritten)

  const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
  await writeDeclaration(file)

  expect(await readFile(file, 'utf-8')).toBe(handWritten)
  expect(warn).toHaveBeenCalledOnce()
})
