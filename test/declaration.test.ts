import { mkdtemp, readdir, readFile, rm, stat, utimes, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import ts from 'typescript'
import { afterEach, expect, it, vi } from 'vitest'
import { runtimeModuleCode, virtualModuleId } from '../src/constant'
import { getDeclaration, writeDeclaration } from '../src/declaration'

let dir: string | undefined

/** Layout names the tests pretend the project has. */
const layoutNames = ['posts', 'default']

afterEach(async () => {
  vi.restoreAllMocks()
  if (dir)
    await rm(dir, { recursive: true, force: true })
  dir = undefined
})

async function getDir(): Promise<string> {
  dir = await mkdtemp(join(tmpdir(), 'uni-layouts-'))
  return dir
}

function getExports(code: string): string[] {
  return [
    ...code.matchAll(/export (?:function|const|let|class) (\w+)/g),
  ]
    .map(match => match[1])
}

it('generated declaration is valid TypeScript', () => {
  const { diagnostics } = ts.transpileModule(getDeclaration(layoutNames), {
    reportDiagnostics: true,
  })
  expect(diagnostics ?? []).toHaveLength(0)
})

it('lists every layout under its name, sorted', () => {
  const declaration = getDeclaration(['posts', 'default'])
  expect(declaration).toContain('interface UniHelperUniLayouts {\n  default: true\n  posts: true\n}')
  expect(declaration).toContain('export type LayoutKey = keyof UniHelperUniLayouts extends never ? string : keyof UniHelperUniLayouts')
})

it('lists a layout name once', () => {
  // `a.vue` and `a/index.vue` derive the same name, and a duplicate interface
  // member would not compile
  const declaration = getDeclaration(['a', 'a'])
  expect(declaration.match(/\ba: true/g)).toHaveLength(1)
})

it('quotes a layout name that is not a plain identifier', () => {
  // `1room.vue` derives the name `1room`, and `1room: true` does not parse
  expect(getDeclaration(['1room'])).toContain('"1room": true')
})

it('escapes a quote inside a layout name', () => {
  // `foo'bar.vue` derives the name `foo'bar`; a hand-made quote would end the key
  const declaration = getDeclaration(['foo\'bar'])
  expect(declaration).toContain('"foo\'bar": true')
  expect(ts.transpileModule(declaration, { reportDiagnostics: true }).diagnostics ?? []).toHaveLength(0)
})

it('falls back to string when the project has no layout', () => {
  const declaration = getDeclaration([])
  expect(declaration).toContain('interface UniHelperUniLayouts {\n\n}')
  // an empty interface makes `keyof` never, which would reject every value
  expect(declaration).toContain('keyof UniHelperUniLayouts extends never ? string')
})

it('generated declaration declares exactly the virtual module exports', () => {
  const declaration = getDeclaration(layoutNames)
  expect(declaration).toContain(`'${virtualModuleId}'`)

  const runtimeExports = getExports(runtimeModuleCode)
  expect(runtimeExports.length).toBeGreaterThan(0)
  // an export that only the declaration has would override the same name from
  // client.d.ts without any error, so the sets must match
  expect(getExports(declaration).sort()).toEqual(runtimeExports.sort())
})

it('writes the declaration file', async () => {
  const file = join(await getDir(), 'types', 'uni-layouts.d.ts')
  await writeDeclaration(file, layoutNames)
  expect(await readFile(file, 'utf-8')).toBe(getDeclaration(layoutNames))
})

it('leaves no temporary file behind', async () => {
  const dirPath = await getDir()
  await writeDeclaration(join(dirPath, 'uni-layouts.d.ts'), layoutNames)
  expect(await readdir(dirPath)).toEqual(['uni-layouts.d.ts'])
})

it('leaves an up-to-date file untouched', async () => {
  const file = join(await getDir(), 'uni-layouts.d.ts')
  await writeDeclaration(file, layoutNames)

  // a rewrite would reset the timestamp
  const old = new Date(2000, 0, 1)
  await utimes(file, old, old)
  await writeDeclaration(file, layoutNames)
  expect((await stat(file)).mtime.getFullYear()).toBe(2000)
})

it('updates a file from an older version of the plugin', async () => {
  const file = join(await getDir(), 'uni-layouts.d.ts')
  await writeFile(file, '// Generated by vite-plugin-uni-layouts\n\nstale declaration\n')
  await writeDeclaration(file, layoutNames)
  expect(await readFile(file, 'utf-8')).toBe(getDeclaration(layoutNames))
})

it('does not overwrite a hand-written file', async () => {
  const file = join(await getDir(), 'uni-layouts.d.ts')
  const handWritten = 'declare module \'my-types\' {}\n'
  await writeFile(file, handWritten)

  const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
  await writeDeclaration(file, layoutNames)

  expect(await readFile(file, 'utf-8')).toBe(handWritten)
  expect(warn).toHaveBeenCalledOnce()
})
